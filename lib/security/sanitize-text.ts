/**
 * 入力文字列からHTMLタグと制御文字を取り除く軽量サニタイズ。
 *
 * 用途: /account-recovery のような「入力内容がそのままDBに保存され、将来的に
 * 管理者向け画面等で表示される可能性がある」フォームで、格納型XSS・ログ表示崩れ・
 * 制御文字によるターミナル汚染を防ぐための一次防御。リッチテキストの許可等は
 * 想定しておらず、常にプレーンテキストとして扱う前提。
 *
 * 改行(\n)・タブ(\t)・復帰(\r)は入力として自然なため保持し、それ以外の制御文字
 * （C0制御文字・DEL）のみ除去する。
 */
export function sanitizeText(value: string): string {
  return value
    .replace(/<[^>]*>/g, "") // 簡易的なHTMLタグ除去（リッチテキストは想定しないため十分）
    .replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F\u007F]/g, "") // 制御文字除去(改行・タブ・復帰は保持)
    .trim();
}
