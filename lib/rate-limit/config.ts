/**
 * 新規登録のレート制限設定（調整はここだけで行う）。
 *
 * ★アプリ側の制限であり、Supabase Auth側の制限（メール送信数・サインアップ回数・CAPTCHA）とは別。
 *   Supabase側の上限はDashboard（Authentication > Rate Limits）で別に設定されており、ここからは確認できない。
 *
 * 想定: 店舗・説明会・学校など、同じネットワーク（同じIP）から複数人が登録する。
 *   IP単位  : 大量の異常試行を抑える安全弁。通常の共有ネットワーク利用では到達しない値にする。
 *             1時間120回 = 50人が1人あたり2回（入力ミス・再送を含む）試しても余裕がある。平均で2回/分以下。
 *             前回までの10回/時は、同じ店舗の10人弱で止まり、別人の登録を妨げていた。
 *   メール単位: 同じ宛先へ確認メールを繰り返し送らせない主たる制限。1時間5回（以前は3回）。
 *             入力ミス・メール未達の再送を許しつつ、特定アドレスへのメール爆撃は抑える。
 *   IP不明  : 前段からIPが取れない場合、全員を1つの厳しいカウンターに集約しない。
 *             IPでは区別できないため、メール単位の制限を主とし、全体の安全弁だけを緩く置く（1時間600回）。
 * ★メール単位の5回は厳密な上限ではない（同時要求・遅延確定・確定通知の失敗で超え得る。0055の「限界」参照）。
 *   CAPTCHA検証に失敗した要求（captcha_failed）はメール単位の枠を消費しない（予約を返却する）。IP単位は消費したまま。
 * 失敗した試行も数える（失敗なら無制限に再試行できる仕組みにはしない）。
 * Turnstile（Bot確認）は制限より前に必ず通す（トークン無しは制限に到達する前に拒否）。
 */
export const SIGNUP_RATE_LIMITS = {
  windowMs: 60 * 60 * 1000,
  perEmail: 5,
  /** メール単位の「検証中（Supabase Authの応答待ち）」の同時数の上限。多いほど正常な本人は弾かれにくいが、
   *  同時の正常要求で perEmail を超えて確認メールが出得る（最大で perEmail - 1 + この値）。 */
  perEmailInflight: 3,
  /** 検証中の予約が、結果の通知なしに残った場合に枠から外れるまでの時間（通信切断・プロセス終了からの回復時間）。 */
  pendingTtlMs: 60 * 1000,
  perIp: 120,
  noIp: 600,
} as const;
